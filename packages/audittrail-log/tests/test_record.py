def log_lines(vector: Path) -> list[bytes]:
    """Every line of the vector's `.jsonl` files in name order, without the newline."""
    lines: list[bytes] = []
    for f in sorted(vector.glob("*.jsonl")):
        data = f.read_bytes()
        lines.extend(data.removesuffix(b"\n").split(b"\n"))
    return lines


def first_failing_check(lines: list[bytes]) -> int:
    """The check number of the first line `Record.from_line` rejects, or 0."""
    for line in lines:
        try:
            Record.from_line(line)
        except RecordError as e:
            return e.check
    return 0


def vector_dirs(vectors_dir: Path, kind: str) -> list[Path]:
    """The vector directories under `kind`, sorted. Fails if there are none."""
    dirs = sorted(p for p in (vectors_dir / kind).iterdir() if p.is_dir())
    assert dirs, f"no {kind} vectors under {vectors_dir}"
    return dirs


# --- positive vectors ------------------------------------------------------


def test_every_positive_vector_line_parses_round_trips_and_hashes(vectors_dir: Path) -> None:
    """Each line parses, serializes back to the same bytes, and hashes to `vector.hash`."""
    for vector in vector_dirs(vectors_dir, "positive"):
        lines = log_lines(vector)
        want = (vector / "vector.hash").read_text(encoding="ascii").split()
        assert len(want) == len(lines), vector.name
        for line, expected_hash in zip(lines, want, strict=True):
            record = Record.from_line(line)
            assert record.line() == line, vector.name
            assert record.hash() == expected_hash, vector.name


def test_positive_vectors_cover_every_record_type(vectors_dir: Path) -> None:
    """The positive set exercises all five record types, so the type rules are all pinned."""
    seen = {
        Record.from_line(line).type
        for vector in vector_dirs(vectors_dir, "positive")
        for line in log_lines(vector)
    }
    assert seen == {"boot", "decision", "heartbeat", "anchor", "rotation"}


# --- negative vectors ------------------------------------------------------


def test_every_negative_vector_fails_at_its_expected_check(vectors_dir: Path) -> None:
    """Checks 1, 2 and 4 are Record's; a vector expecting 5 or 9 must parse cleanly here."""
    for vector in vector_dirs(vectors_dir, "negative"):
        expect = (vector / "vector.expect").read_text(encoding="ascii")
        m = re.fullmatch(r"check=(\d+) exit=2\n", expect)
        assert m, f"{vector.name}: bad vector.expect {expect!r}"
        want = int(m.group(1))
        got = first_failing_check(log_lines(vector))
        assert got == (want if want in {1, 2, 4} else 0), vector.name


# --- I8: no text channel ---------------------------------------------------


def test_every_record_field_has_a_regex_enum_or_integer_rule() -> None:
    """Static: each `str` field is in STRING_RULES, each `int` field in INT_FIELDS, nothing else."""
    hints = typing.get_type_hints(Record)
    assert hints, "Record has no fields"
    for name, annotation in hints.items():
        if annotation is str:
            rule = STRING_RULES[name]
            assert isinstance(rule, re.Pattern | frozenset), name
        else:
            assert annotation is int and name in INT_FIELDS, name
    assert set(STRING_RULES) | set(INT_FIELDS) == set(hints)
    assert not set(STRING_RULES) & set(INT_FIELDS)


def genesis_boot(vectors_dir: Path) -> Record:
    """The genesis record of the `genesis-boot` vector. Use only for genesis and boot rules."""
    return Record.from_line(log_lines(vectors_dir / "positive" / "genesis-boot")[0])


def approve_decision(vectors_dir: Path) -> Record:
    """The approving decision of the `decision-approve` vector.

    Field-rule tests use this record, not the boot: on a `decision` nothing but `since_hb` is
    fixed by type, so a rejection can only come from the field's own regex, enum or range.
    """
    record = Record.from_line(log_lines(vectors_dir / "positive" / "decision-approve")[1])
    assert record.type == "decision" and record.decision == "approve"
    return record


