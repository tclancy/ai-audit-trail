"""Record: strict parse, round trip, hashing, and the no-text-channel rule (I8).

Every expectation here comes from `spec/vectors/` or from SPEC §3; nothing is
generated by the code under test.
"""

from __future__ import annotations

import copy
import dataclasses
import re
import typing
from pathlib import Path
from typing import Any

import pytest
from audittrail.record import (
    INT_FIELDS,
    STRING_RULES,
    ZERO_HASH,
    ChainError,
    ParseError,
    Record,
    RecordError,
    SchemaError,
    canonical_bytes,
)


def log_lines(vector: Path) -> list[bytes]:
    """Every line of the vector's `.jsonl` files in name order, without the newline."""
    lines: list[bytes] = []
    for f in sorted(vector.glob("*.jsonl")):
        data = f.read_bytes()
        lines.extend(data.removesuffix(b"\n").split(b"\n"))
    return lines


def first_failing_check(lines: list[bytes]) -> int:
    """The check number of the first line `Record.from_line` rejects, or 0."""
    for line in lines:
        try:
            Record.from_line(line)
        except RecordError as e:
            return e.check
    return 0


def vector_dirs(vectors_dir: Path, kind: str) -> list[Path]:
    """The vector directories under `kind`, sorted. Fails if there are none."""
    dirs = sorted(p for p in (vectors_dir / kind).iterdir() if p.is_dir())
    assert dirs, f"no {kind} vectors under {vectors_dir}"
    return dirs


# --- positive vectors ------------------------------------------------------


def test_every_positive_vector_line_parses_round_trips_and_hashes(vectors_dir: Path) -> None:
    """Each line parses, serializes back to the same bytes, and hashes to `vector.hash`."""
    for vector in vector_dirs(vectors_dir, "positive"):
        lines = log_lines(vector)
        want = (vector / "vector.hash").read_text(encoding="ascii").split()
        assert len(want) == len(lines), vector.name
        for line, expected_hash in zip(lines, want, strict=True):
            record = Record.from_line(line)
            assert record.line() == line, vector.name
            assert record.hash() == expected_hash, vector.name


def test_positive_vectors_cover_every_record_type(vectors_dir: Path) -> None:
    """The positive set exercises all five record types, so the type rules are all pinned."""
    seen = {
        Record.from_line(line).type
        for vector in vector_dirs(vectors_dir, "positive")
        for line in log_lines(vector)
    }
    assert seen == {"boot", "decision", "heartbeat", "anchor", "rotation"}


# --- negative vectors ------------------------------------------------------


def test_every_negative_vector_fails_at_its_expected_check(vectors_dir: Path) -> None:
    """Checks 1, 2 and 4 are Record's; a vector expecting 5 or 9 must parse cleanly here."""
    for vector in vector_dirs(vectors_dir, "negative"):
        expect = (vector / "vector.expect").read_text(encoding="ascii")
        m = re.fullmatch(r"check=(\d+) exit=2\n", expect)
        assert m, f"{vector.name}: bad vector.expect {expect!r}"
        want = int(m.group(1))
        got = first_failing_check(log_lines(vector))
        assert got == (want if want in {1, 2, 4} else 0), vector.name


# --- I8: no text channel ---------------------------------------------------


def test_every_record_field_has_a_regex_enum_or_integer_rule() -> None:
    """Static: each `str` field is in STRING_RULES, each `int` field in INT_FIELDS, nothing else."""
    hints = typing.get_type_hints(Record)
    assert hints, "Record has no fields"
    for name, annotation in hints.items():
        if annotation is str:
            rule = STRING_RULES[name]
            assert isinstance(rule, re.Pattern | frozenset), name
        else:
            assert annotation is int and name in INT_FIELDS, name
    assert set(STRING_RULES) | set(INT_FIELDS) == set(hints)
    assert not set(STRING_RULES) & set(INT_FIELDS)


def genesis_boot(vectors_dir: Path) -> Record:
    """The genesis record of the `genesis-boot` vector."""
    return Record.from_line(log_lines(vectors_dir / "positive" / "genesis-boot")[0])


@pytest.mark.parametrize("field", sorted(STRING_RULES))
def test_free_text_is_rejected_in_every_string_field(vectors_dir: Path, field: str) -> None:
    """A value with a space never constructs, whatever the field."""
    change: dict[str, Any] = {field: "free text here"}
    with pytest.raises(SchemaError):
        dataclasses.replace(genesis_boot(vectors_dir), **change)


@pytest.mark.parametrize("field", sorted(INT_FIELDS))
@pytest.mark.parametrize("value", [True, -1, 2**53, 1.0])
def test_bad_integers_are_rejected(vectors_dir: Path, field: str, value: object) -> None:
    """Bools, negatives, 2^53 and floats are not integers in [0, 2^53)."""
    change: dict[str, Any] = {field: value}
    with pytest.raises(SchemaError):
        dataclasses.replace(genesis_boot(vectors_dir), **change)


def test_genesis_requires_seq_zero_boot_and_zero_prev(vectors_dir: Path) -> None:
    """`prev` is the zero-hash exactly at `seq == 0`, and `seq == 0` is a `boot`."""
    boot = genesis_boot(vectors_dir)
    with pytest.raises(ChainError):
        dataclasses.replace(boot, prev="sha256:" + "a" * 64)
    with pytest.raises(ChainError):
        dataclasses.replace(boot, seq=1)
    with pytest.raises(ChainError):
        dataclasses.replace(boot, type="decision")


# --- parser edge cases not covered by a vector ---------------------------


@pytest.mark.parametrize(
    "line",
    [b"", b"[]", b'"x"', b"1", b"null", b"{", b'{"a":1}\n', b'{"a":true}', b'{"a":1.5e0}'],
)
def test_parse_rejects_non_object_lines_and_trailing_newline(line: bytes) -> None:
    """Non-objects, partial JSON, and a trailing newline are check-1 or schema failures."""
    with pytest.raises(RecordError):
        Record.from_line(line)


def test_parse_error_carries_check_one_and_schema_error_check_two() -> None:
    """The error types map to SPEC §5 check numbers."""
    assert ParseError.check == 1
    assert SchemaError.check == 2
    assert ChainError.check == 4


def test_canonical_bytes_refuses_non_ascii_and_floats() -> None:
    """The canonical alphabet is printable ASCII and integers; nothing else serializes."""
    with pytest.raises(ParseError):
        canonical_bytes({"a": "é"})
    with pytest.raises(ParseError):
        canonical_bytes({"a": "\ud800"})
    with pytest.raises(ParseError):
        canonical_bytes({"a": 1.0})
    with pytest.raises(ParseError):
        canonical_bytes({"a": "tab\there"})
    assert canonical_bytes({"b": 1, "a": "x"}) == b'{"a":"x","b":1}'


def test_zero_hash_constant() -> None:
    """The zero-hash is `sha256:` and 64 zeros."""
    assert ZERO_HASH == "sha256:" + "0" * 64


# --- process hygiene (SPEC §4, listed as tests, not invariants) ------------


def test_record_is_final_and_not_copyable_by_protocol(vectors_dir: Path) -> None:
    """Subclassing raises; the copy and persistence protocols raise."""
    with pytest.raises(TypeError):

        class Sub(Record):
            """Never constructed; the class statement itself must raise."""

    with pytest.raises(TypeError):
        copy.copy(genesis_boot(vectors_dir))
